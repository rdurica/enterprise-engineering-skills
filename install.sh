#!/usr/bin/env bash
# Link this pack into Claude Code, Codex, Cursor, opencode and Pi, or only the tools you use:
#   Claude Code  ~/.claude/skills/<skill>, ~/.claude/agents/<agent>.md
#   Codex        ~/.agents/skills/<skill> (shared with Cursor, opencode and Pi), ~/.codex/agents/<agent>.toml
#   Cursor       ~/.cursor/agents/<agent>.md; skills come from ~/.agents/skills
#   opencode     ~/.config/opencode/agents/<agent>.md; skills come from ~/.agents/skills;
#                with opencode installed, the pack's models are merged into opencode.json (scripts/opencode-config)
#   Pi           ~/.pi/agent/agents/<agent>.md, prompts and the subagent tool in ~/.pi/agent/extensions/subagent/
# Agents link to generated/<provider>/agents/, built by scripts/build-agents.
# Without a terminal and without flags the installer links every provider. Re-run after changing a
# skill or agent: missing links are added, broken ones repaired and links of unselected tools removed.
set -euo pipefail

pack="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
claude_dir="${CLAUDE_CONFIG_DIR:-$HOME/.claude}"
agents_skills_dir="$HOME/.agents/skills"
codex_dir="${CODEX_HOME:-$HOME/.codex}"
cursor_dir="$HOME/.cursor"
opencode_dir="${XDG_CONFIG_HOME:-$HOME/.config}/opencode"
pi_dir="${PI_CODING_AGENT_DIR:-$HOME/.pi/agent}"
# Agent files written by older versions of this script, replaced by links.
old_generated_marker="# Generated by enterprise-engineering-skills/install.sh"

provider_order=(claude codex cursor opencode pi)
selection=()
actions=()
dry_run=0

usage() {
  cat <<'EOF'
Usage: ./install.sh [--all | --providers <list>] [--interactive] [--yes] [--dry-run]

  --all                link every provider
  --providers <list>   comma or space separated: claude, codex, cursor, opencode, pi, all, none
  --interactive        ask which tools to use, even when stdin is not a terminal
  --yes                apply the plan without asking for confirmation
  --dry-run            print the plan and write nothing
  --help               show this help

Without --all or --providers the installer asks on a terminal and behaves like --all otherwise.
EOF
}

usage_error() {
  printf 'install.sh: %s\n\n' "$1" >&2
  usage >&2
  exit 2
}

# ---------------------------------------------------------------- plan helpers

is_pack_link() { # <path>: a symlink whose target is inside this pack, even when it dangles
  [[ -L "$1" ]] || return 1
  local target
  target="$(readlink -f "$1" 2>/dev/null || true)"
  if [[ "$target" == "$pack" || "$target" == "$pack"/* ]]; then
    return 0
  fi
  # readlink -f gives up when a parent directory of a dangling target is gone; the raw target still
  # names this pack, so a link left by an uninstalled skill or agent is still cleaned up.
  target="$(readlink "$1" 2>/dev/null || true)"
  [[ "$target" == "$pack" || "$target" == "$pack"/* ]]
}

is_old_generated() {
  [[ -f "$1" && ! -L "$1" ]] && head -n 2 "$1" | grep -qF "$old_generated_marker"
}

# Every action is printed once while the plan is built and recorded for the apply step. Cleanup and
# pruning can reach the same destination, so an action already in the plan is recorded only once.
record() { # record <action> <dest> [src]
  local action="$1" dest="$2" src="${3:-}" entry
  for entry in ${actions[@]+"${actions[@]}"}; do
    if [[ "$entry" == "$action"$'\t'"$dest"$'\t'"$src" ]]; then return 0; fi
  done
  if [[ -n "$src" ]]; then
    printf '%-8s%s -> %s\n' "$action" "$dest" "$src"
  else
    printf '%-8s%s\n' "$action" "$dest"
  fi
  actions+=("$action"$'\t'"$dest"$'\t'"$src")
}

# Reconcile one destination with <src>: keep an identical link, replace a link into this pack or an
# old generated file, add a missing one and leave anything else to the user.
link() {
  local src="$1" dest="$2"
  if [[ -L "$dest" ]]; then
    local current
    current="$(readlink -f "$dest" || true)"
    if [[ "$current" == "$src" ]]; then
      record ok "$dest"
      return 0
    fi
    # Replace only links into this pack or dangling links, never someone else's skill.
    if [[ "$current" == "$pack"/* || ! -e "$dest" ]]; then
      record relink "$dest" "$src"
      return 0
    fi
    printf 'skip    %s (links to %s; remove it manually to use this pack)\n' "$dest" "$current" >&2
    return 0
  elif is_old_generated "$dest"; then
    record relink "$dest" "$src"
    return 0
  elif [[ -e "$dest" ]]; then
    printf 'skip    %s (real file or directory; remove it manually to use this pack)\n' "$dest" >&2
    return 0
  fi
  record link "$dest" "$src"
}

link_skills() {
  local dest_dir="$1" skill
  for skill in "$pack"/skills/*/ "$pack"/skills/personal/*/; do
    skill="${skill%/}"
    [[ -f "$skill/SKILL.md" ]] || continue
    link "$skill" "$dest_dir/$(basename "$skill")"
  done
}

link_agents() {
  local provider="$1" dest_dir="$2" agent
  for agent in "$pack/generated/$provider/agents"/*; do
    [[ -f "$agent" ]] || continue
    link "$agent" "$dest_dir/$(basename "$agent")"
  done
}

# Pi slash commands that make the documented `/ees-<name>` spelling work (Pi calls skills
# `/skill:<name>`).
link_prompts() {
  local dest_dir="$1" prompt
  for prompt in "$pack/generated/pi/prompts"/*.md; do
    [[ -f "$prompt" ]] || continue
    link "$prompt" "$dest_dir/$(basename "$prompt")"
  done
}

# Remove dangling links into this pack and old generated files, left behind by renamed or deleted
# skills and agents. Runs in every managed destination, selected or not.
cleanup() {
  local dest
  for dest in "$@"; do
    if [[ -L "$dest" ]]; then
      if [[ ! -e "$dest" ]] && is_pack_link "$dest"; then
        record unlink "$dest"
      fi
    elif is_old_generated "$dest"; then
      record unlink "$dest"
    fi
  done
  return 0
}

# Remove every link into this pack, for destinations the selection does not need.
unlink_all() {
  local dest
  for dest in "$@"; do
    is_pack_link "$dest" || continue
    record unlink "$dest"
  done
  return 0
}

prune_extension() {
  local dest="$pi_dir/extensions/subagent"
  if is_pack_link "$dest"; then
    record unlink "$dest"
  fi
  return 0
}

# ---------------------------------------------------------------- detection and selection

has_pack_link_in() { # <dir>...: at least one link into this pack
  local dir entry
  for dir in "$@"; do
    [[ -d "$dir" ]] || continue
    for entry in "$dir"/*; do
      is_pack_link "$entry" && return 0
    done
  done
  return 1
}

is_linked() { # <provider>: has at least one link into the pack in a destination only it owns
  case "$1" in
    claude) has_pack_link_in "$claude_dir/skills" "$claude_dir/agents" ;;
    codex) has_pack_link_in "$codex_dir/agents" ;;
    cursor) has_pack_link_in "$cursor_dir/agents" ;;
    opencode) has_pack_link_in "$opencode_dir/agents" ;;
    pi) has_pack_link_in "$pi_dir/agents" "$pi_dir/prompts" || is_pack_link "$pi_dir/extensions/subagent" ;;
  esac
}

is_present() { # <provider>: its CLI is on PATH or its config directory exists
  case "$1" in
    claude) command -v claude >/dev/null 2>&1 || [[ -d "$claude_dir" ]] ;;
    codex) command -v codex >/dev/null 2>&1 || [[ -d "$codex_dir" ]] ;;
    cursor) command -v cursor >/dev/null 2>&1 || command -v cursor-agent >/dev/null 2>&1 || [[ -d "$cursor_dir" ]] ;;
    opencode) command -v opencode >/dev/null 2>&1 || [[ -d "$opencode_dir" ]] ;;
    pi) command -v pi >/dev/null 2>&1 || [[ -d "$pi_dir" ]] ;;
  esac
}

# Bash 3.2 has no associative arrays, so membership is a plain linear scan.
in_list() { # <value> [<list>...]
  local value="$1" item
  shift
  for item in "$@"; do
    [[ "$item" == "$value" ]] && return 0
  done
  return 1
}

is_selected() { in_list "$1" ${selection[@]+"${selection[@]}"}; }

# Store <list> as the selection, in provider order and without duplicates.
select_from() {
  local p
  selection=()
  for p in "${provider_order[@]}"; do
    if in_list "$p" "$@"; then selection+=("$p"); fi
  done
}

lower() { # <string>: lowercase, without bash 4's case-modification expansion
  printf '%s' "$1" | tr '[:upper:]' '[:lower:]'
}

shared_selected() { # any provider that reads ~/.agents/skills
  is_selected codex || is_selected cursor || is_selected opencode || is_selected pi
}

provider_label() {
  case "$1" in
    claude) printf 'Claude Code' ;;
    codex) printf 'Codex' ;;
    cursor) printf 'Cursor' ;;
    opencode) printf 'opencode' ;;
    pi) printf 'Pi' ;;
  esac
}

provider_note() {
  if is_linked "$1" && is_present "$1"; then
    printf 'linked, installed'
  elif is_linked "$1"; then
    printf 'linked'
  elif is_present "$1"; then
    printf 'installed'
  else
    printf 'not found'
  fi
}

parse_providers() {
  local raw="$1" token
  local -a tokens=() want=()
  raw="${raw//,/ }"
  read -r -a tokens <<<"$raw"
  if (( ${#tokens[@]} == 0 )); then
    usage_error "--providers needs a list of providers; use 'none' to remove every link"
  fi
  for token in "${tokens[@]}"; do
    case "$token" in
      all) want=("${provider_order[@]}") ;;
      none) want=() ;;
      claude|codex|cursor|opencode|pi) want+=("$token") ;;
      *) usage_error "unknown provider: $token" ;;
    esac
  done
  select_from ${want[@]+"${want[@]}"}
}

# Numbered provider picker. An empty answer keeps the default, `all` and `none` replace it, and
# numbers (comma or space separated) replace it. Invalid input re-prompts; EOF aborts.
wizard() {
  local p i marker note line trimmed token valid
  local -a defaults=() tokens=() want=()
  for p in "${provider_order[@]}"; do
    if is_linked "$p"; then defaults+=("$p"); fi
  done
  if (( ${#defaults[@]} == 0 )); then defaults=("${provider_order[@]}"); fi

  while true; do
    printf '\nSelect the tools to link (Enter keeps the default):\n'
    for i in "${!provider_order[@]}"; do
      p="${provider_order[$i]}"
      marker=" "
      if in_list "$p" "${defaults[@]}"; then marker="x"; fi
      note="$(provider_note "$p")"
      printf '  %d) %-12s [%s] %s\n' "$((i + 1))" "$(provider_label "$p")" "$marker" "$note"
    done
    printf 'Selection: '
    if ! IFS= read -r line; then
      printf '\n' >&2
      printf 'No interactive input; nothing was written.\n' >&2
      exit 1
    fi
    trimmed="${line#"${line%%[![:space:]]*}"}"
    trimmed="${trimmed%"${trimmed##*[![:space:]]}"}"
    if [[ -z "$trimmed" ]]; then
      selection=("${defaults[@]}")
      return 0
    fi
    case "$(lower "$trimmed")" in
      all)
        selection=("${provider_order[@]}")
        return 0
        ;;
      none)
        selection=()
        return 0
        ;;
    esac
    trimmed="${trimmed//,/ }"
    read -r -a tokens <<<"$trimmed"
    want=()
    valid=1
    for token in ${tokens[@]+"${tokens[@]}"}; do
      if [[ "$token" =~ ^[1-5]$ ]]; then
        want+=("${provider_order[$((token - 1))]}")
      else
        valid=0
        break
      fi
    done
    if (( valid )); then
      select_from ${want[@]+"${want[@]}"}
      return 0
    fi
    printf 'Invalid selection: %s\n' "$line" >&2
  done
}

confirm_plan() {
  local answer
  printf 'Apply this plan? [Y/n] '
  if ! IFS= read -r answer; then
    printf '\n' >&2
    printf 'No confirmation input; nothing was written.\n' >&2
    exit 1
  fi
  printf '\n'
  answer="${answer#"${answer%%[![:space:]]*}"}"
  answer="${answer%"${answer##*[![:space:]]}"}"
  case "$(lower "$answer")" in
    ''|y|yes) return 0 ;;
  esac
  printf 'Nothing was written.\n'
  exit 0
}

# ---------------------------------------------------------------- plan

build_plan() {
  # Cleanup runs everywhere so renamed or deleted skills and agents disappear on the next run.
  cleanup "$claude_dir"/skills/* "$agents_skills_dir"/* "$claude_dir"/agents/* \
    "$codex_dir"/agents/* "$cursor_dir"/agents/* "$opencode_dir"/agents/* \
    "$cursor_dir"/skills/* "$pi_dir"/agents/* "$pi_dir"/prompts/*.md "$pi_dir/extensions/subagent"

  # Prune every managed destination the selection does not need.
  if ! is_selected claude; then unlink_all "$claude_dir"/skills/* "$claude_dir"/agents/*; fi
  if ! shared_selected; then unlink_all "$agents_skills_dir"/*; fi
  if ! is_selected codex; then unlink_all "$codex_dir"/agents/*; fi
  if ! is_selected cursor; then unlink_all "$cursor_dir"/agents/*; fi
  if ! is_selected opencode; then unlink_all "$opencode_dir"/agents/*; fi
  if ! is_selected pi; then
    unlink_all "$pi_dir"/agents/* "$pi_dir"/prompts/*.md
    prune_extension
  fi
  # ~/.cursor/skills would duplicate the skills Cursor already reads from ~/.agents/skills.
  unlink_all "$cursor_dir"/skills/*

  if is_selected claude; then
    link_skills "$claude_dir/skills"
    link_agents claude "$claude_dir/agents"
  fi
  if is_selected codex; then link_agents codex "$codex_dir/agents"; fi
  if is_selected cursor; then link_agents cursor "$cursor_dir/agents"; fi
  if is_selected opencode; then link_agents opencode "$opencode_dir/agents"; fi
  if shared_selected; then link_skills "$agents_skills_dir"; fi
  if is_selected pi; then
    link_agents pi "$pi_dir/agents"
    link_prompts "$pi_dir/prompts"
    # Pi has no built-in subagents; its subagent tool ships as an example extension, kept in this pack.
    link "$pack/pi/extensions/subagent" "$pi_dir/extensions/subagent"
  fi
}

# ---------------------------------------------------------------- apply

apply_plan() {
  local entry action dest src parent
  for entry in ${actions[@]+"${actions[@]}"}; do
    IFS=$'\t' read -r action dest src <<<"$entry"
    case "$action" in
      link|relink)
        parent="${dest%/*}"
        [[ -d "$parent" ]] || mkdir -p "$parent"
        ln -sfn "$src" "$dest"
        ;;
      unlink) rm -f "$dest" ;;
    esac
  done
}

opencode_config() {
  if (( dry_run )); then
    "$pack/scripts/opencode-config" --dry-run "$opencode_dir"
  else
    "$pack/scripts/opencode-config" "$opencode_dir"
  fi
}

# ---------------------------------------------------------------- arguments and main

flag_all=0
have_providers=0
flag_interactive=0
assume_yes=0
providers_raw=""

while (( $# > 0 )); do
  case "$1" in
    --all) flag_all=1 ;;
    --providers)
      shift
      (( $# > 0 )) || usage_error "--providers needs a list of providers"
      providers_raw="$1"
      have_providers=1
      ;;
    --providers=*)
      providers_raw="${1#--providers=}"
      have_providers=1
      ;;
    --interactive) flag_interactive=1 ;;
    --yes) assume_yes=1 ;;
    --dry-run) dry_run=1 ;;
    --help|-h) usage; exit 0 ;;
    *) usage_error "unknown option: $1" ;;
  esac
  shift
done

if (( flag_all )) && (( have_providers )); then
  usage_error "--all and --providers cannot be combined"
fi

used_wizard=0
if (( flag_all )); then
  selection=("${provider_order[@]}")
elif (( have_providers )); then
  parse_providers "$providers_raw"
elif (( flag_interactive )) || [[ -t 0 ]]; then
  wizard
  used_wizard=1
else
  selection=("${provider_order[@]}")
fi

build_plan

if (( dry_run )); then
  if is_selected opencode && command -v opencode >/dev/null 2>&1; then
    opencode_config
  fi
else
  if (( ! assume_yes )) && { (( used_wizard )) || [[ -t 0 ]]; }; then
    confirm_plan
  fi
  apply_plan
  if is_selected opencode && command -v opencode >/dev/null 2>&1; then
    opencode_config
  fi
fi

# Keep generated/ in sync with agents/ and agents.toml on every commit in this checkout.
if [[ -z "$(git -C "$pack" config --get core.hooksPath 2>/dev/null || true)" ]]; then
  printf '%-8s%s\n' hooks "core.hooksPath = .githooks"
  (( dry_run )) || git -C "$pack" config core.hooksPath .githooks
fi

if (( dry_run )); then
  echo "Dry run: nothing written."
else
  echo "Done. Start a new Claude Code, Codex, Cursor, opencode or Pi session to pick up the changes."
fi
