#!/usr/bin/env bash
# Link this pack into Claude Code, Codex, Cursor and opencode:
#   Claude Code  ~/.claude/skills/<skill>, ~/.claude/agents/<agent>.md
#   Codex        ~/.agents/skills/<skill> (also read by Cursor), ~/.codex/agents/<agent>.toml
#   Cursor       ~/.cursor/agents/<agent>.md; skills come from ~/.agents/skills and ~/.claude/skills
#   opencode     ~/.config/opencode/agents/<agent>.md; skills come from ~/.agents/skills and ~/.claude/skills
# Agents link to generated/<provider>/agents/, built by scripts/build-agents.
# Re-run after adding, renaming or removing a skill or agent; `git pull` alone updates existing links.
set -euo pipefail

pack="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
claude_dir="${CLAUDE_CONFIG_DIR:-$HOME/.claude}"
agents_skills_dir="$HOME/.agents/skills"
codex_dir="${CODEX_HOME:-$HOME/.codex}"
cursor_dir="$HOME/.cursor"
opencode_dir="${XDG_CONFIG_HOME:-$HOME/.config}/opencode"
# Agent files written by older versions of this script, replaced by links.
old_generated_marker="# Generated by enterprise-engineering-skills/install.sh"
dry_run=0
[[ "${1:-}" == "--dry-run" ]] && dry_run=1

is_old_generated() {
  [[ -f "$1" && ! -L "$1" ]] && head -n 2 "$1" | grep -qF "$old_generated_marker"
}

link() {
  local src="$1" dest="$2"
  if [[ -L "$dest" ]]; then
    local current
    current="$(readlink -f "$dest" || true)"
    if [[ "$current" == "$src" ]]; then
      echo "ok      $dest"
      return
    fi
    # Replace only links into this pack or dangling links, never someone else's skill.
    if [[ "$current" == "$pack"/* || ! -e "$dest" ]]; then
      echo "relink  $dest -> $src"
    else
      echo "skip    $dest (links to $current; remove it manually to use this pack)" >&2
      return
    fi
  elif is_old_generated "$dest"; then
    echo "relink  $dest -> $src"
  elif [[ -e "$dest" ]]; then
    echo "skip    $dest (real file or directory; remove it manually to use this pack)" >&2
    return
  else
    echo "link    $dest -> $src"
  fi
  (( dry_run )) || ln -sfn "$src" "$dest"
}

link_skills() {
  local dest_dir="$1" skill
  for skill in "$pack"/skills/*/ "$pack"/skills/personal/*/; do
    skill="${skill%/}"
    [[ -f "$skill/SKILL.md" ]] || continue
    link "$skill" "$dest_dir/$(basename "$skill")"
  done
}

link_agents() {
  local provider="$1" dest_dir="$2" agent
  for agent in "$pack/generated/$provider/agents"/*; do
    [[ -f "$agent" ]] || continue
    link "$agent" "$dest_dir/$(basename "$agent")"
  done
}

# Remove dangling links into this pack and old generated agents, left behind by renamed or deleted
# skills and agents.
cleanup() {
  local dest
  for dest in "$@"; do
    if [[ -L "$dest" ]]; then
      [[ ! -e "$dest" && "$(readlink "$dest")" == "$pack"/* ]] || continue
    else
      is_old_generated "$dest" || continue
    fi
    echo "unlink  $dest"
    (( dry_run )) || rm "$dest"
  done
}

# Remove every link into this pack, for places the pack no longer installs into.
unlink_all() {
  local dest
  for dest in "$@"; do
    [[ -L "$dest" && "$(readlink "$dest")" == "$pack"/* ]] || continue
    echo "unlink  $dest"
    (( dry_run )) || rm "$dest"
  done
}

(( dry_run )) || mkdir -p "$claude_dir/skills" "$claude_dir/agents" "$agents_skills_dir" "$codex_dir/agents" \
  "$cursor_dir/agents" "$opencode_dir/agents"

link_skills "$claude_dir/skills"
link_skills "$agents_skills_dir"
link_agents claude "$claude_dir/agents"
link_agents codex "$codex_dir/agents"
link_agents cursor "$cursor_dir/agents"
link_agents opencode "$opencode_dir/agents"
cleanup "$claude_dir"/skills/* "$agents_skills_dir"/* "$claude_dir"/agents/*.md "$codex_dir"/agents/*.toml \
  "$cursor_dir"/agents/*.md "$opencode_dir"/agents/*.md
# ~/.cursor/skills would duplicate the skills Cursor already reads from ~/.agents/skills.
unlink_all "$cursor_dir"/skills/*

# Keep generated/ in sync with agents/ and agents.toml on every commit in this checkout.
if [[ -z "$(git -C "$pack" config --get core.hooksPath || true)" ]]; then
  echo "hooks   core.hooksPath = .githooks"
  (( dry_run )) || git -C "$pack" config core.hooksPath .githooks
fi

echo "Done. Start a new Claude Code, Codex, Cursor or opencode session to pick up the changes."
